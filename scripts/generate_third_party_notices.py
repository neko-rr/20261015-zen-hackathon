#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""サードパーティ NOTICE を生成し、docs と画面の JSON を揃える。

使い方:
  python scripts/generate_third_party_notices.py
  python scripts/generate_third_party_notices.py --check

正本（手）: docs/legal/services.json
自動: docs/legal/generated/* と apps/web/src/data/generated/third_party_notices.json

依存の自動更新はしない。提出後のデフォルトブランチ凍結に合わせ、Renovate は置かない。
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from importlib.metadata import PackageNotFoundError, metadata
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
DOCS_LEGAL = ROOT / "docs" / "legal"
DOCS_GEN = DOCS_LEGAL / "generated"
WEB_GEN = ROOT / "apps" / "web" / "src" / "data" / "generated"
SERVICES_PATH = DOCS_LEGAL / "services.json"
NPM_PACKAGE_JSON = ROOT / "apps" / "web" / "package.json"
PIP_REQUIREMENTS = ROOT / "apps" / "api" / "requirements.txt"
NODE_MODULES = ROOT / "apps" / "web" / "node_modules"

HEADER_MD = (
    "<!-- GENERATED by scripts/generate_third_party_notices.py — 手編集禁止。"
    " 再生成: python scripts/generate_third_party_notices.py -->\n"
)

APP_NOTICE_JA = (
    "このリポジトリのソースは All Rights Reserved（直下の LICENSE）です。"
    "このページは、画面と API が直接依存するオープンソースと、外部サービスの表示メモです。"
)

SKIP_NPM_NAMES = {"web"}
_REQ_NAME_RE = re.compile(r"^[A-Za-z0-9_.-]+$")


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _license_to_str(value: Any) -> str:
    if value is None:
        return "UNKNOWN"
    if isinstance(value, str):
        text = value.strip()
        return text or "UNKNOWN"
    if isinstance(value, dict):
        kind = value.get("type")
        if isinstance(kind, str) and kind.strip():
            return kind.strip()
    if isinstance(value, list):
        parts = [p for p in (_license_to_str(item) for item in value) if p != "UNKNOWN"]
        return " OR ".join(parts) if parts else "UNKNOWN"
    return str(value)


def _homepage(pkg: dict[str, Any]) -> str:
    home = pkg.get("homepage")
    if isinstance(home, str) and home.startswith("http"):
        return home
    repo = pkg.get("repository")
    url = repo if isinstance(repo, str) else ""
    if isinstance(repo, dict):
        raw = repo.get("url")
        url = raw if isinstance(raw, str) else ""
    url = url.removeprefix("git+").replace("git://", "https://")
    if url.endswith(".git"):
        url = url[: -len(".git")]
    if url.startswith("ssh://git@github.com/"):
        url = "https://github.com/" + url.removeprefix("ssh://git@github.com/")
    if url.startswith("git@github.com:"):
        url = "https://github.com/" + url.removeprefix("git@github.com:")
    return url if url.startswith("http") else ""


def load_services() -> list[dict[str, Any]]:
    if not SERVICES_PATH.is_file():
        return []
    data = json.loads(SERVICES_PATH.read_text(encoding="utf-8"))
    items = data.get("services") if isinstance(data, dict) else data
    if not isinstance(items, list):
        return []
    return [item for item in items if isinstance(item, dict)]


def read_direct_npm_deps() -> dict[str, str]:
    if not NPM_PACKAGE_JSON.is_file():
        return {}
    data = json.loads(NPM_PACKAGE_JSON.read_text(encoding="utf-8"))
    deps = data.get("dependencies") or {}
    if not isinstance(deps, dict):
        return {}
    out: dict[str, str] = {}
    for name, ver in deps.items():
        if not isinstance(name, str) or name in SKIP_NPM_NAMES:
            continue
        if isinstance(ver, str):
            out[name] = ver
    return out


def _pkg_json_path(name: str) -> Path:
    return NODE_MODULES.joinpath(*name.split("/"), "package.json")


def collect_npm_packages() -> list[dict[str, Any]]:
    direct = read_direct_npm_deps()
    rows: list[dict[str, Any]] = []
    for name, pinned in sorted(direct.items()):
        path = _pkg_json_path(name)
        pkg = None
        if path.is_file():
            try:
                loaded = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                loaded = None
            pkg = loaded if isinstance(loaded, dict) else None
        version = pinned
        license_name = "UNKNOWN"
        homepage = ""
        if pkg:
            raw_version = pkg.get("version")
            if isinstance(raw_version, str) and raw_version:
                version = raw_version
            license_name = _license_to_str(pkg.get("license"))
            homepage = _homepage(pkg)
        rows.append(
            {
                "name": name,
                "version": version,
                "license": license_name,
                "ecosystem": "npm",
                "homepage": homepage,
            }
        )
    return rows


def parse_requirements_rows(text: str) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    seen: set[str] = set()
    for line in text.splitlines():
        raw = line.strip()
        if not raw or raw.startswith("#") or raw.startswith("-"):
            continue
        base = raw.split(";", 1)[0].strip()
        name = re.split(r"[<>=!~\[]", base, maxsplit=1)[0].strip()
        if not name or not _REQ_NAME_RE.match(name):
            continue
        key = name.lower()
        if key in seen:
            continue
        seen.add(key)
        rows.append({"name": name, "constraint": base[len(name) :].strip()})
    return rows


def _pip_license(name: str) -> str:
    try:
        meta = metadata(name)
    except PackageNotFoundError:
        return "UNKNOWN"
    expression = meta.get("License-Expression")
    if isinstance(expression, str) and expression.strip():
        return expression.strip()
    declared = meta.get("License")
    if isinstance(declared, str) and declared.strip() and declared.strip().upper() != "UNKNOWN":
        return declared.strip()
    classifiers = meta.get_all("Classifier") or []
    found = [
        item.split("::")[-1].strip()
        for item in classifiers
        if isinstance(item, str) and item.startswith("License ::")
    ]
    if found:
        return " OR ".join(found)
    return "UNKNOWN"


def collect_pip_packages() -> list[dict[str, Any]]:
    if not PIP_REQUIREMENTS.is_file():
        return []
    rows: list[dict[str, Any]] = []
    text = PIP_REQUIREMENTS.read_text(encoding="utf-8")
    for item in parse_requirements_rows(text):
        name = item["name"]
        constraint = item["constraint"]
        version = constraint[2:].strip() if constraint.startswith("==") else constraint
        rows.append(
            {
                "name": name,
                "version": version or constraint,
                "license": _pip_license(name),
                "ecosystem": "pip",
                "homepage": "",
            }
        )
    return rows


def build_payload(
    packages: list[dict[str, Any]],
    services: list[dict[str, Any]],
    *,
    generated_at: str,
) -> dict[str, Any]:
    sorted_pkgs = sorted(
        packages,
        key=lambda row: (str(row.get("ecosystem", "")), str(row.get("name", "")).lower()),
    )
    return {
        "generated_at": generated_at,
        "app_notice_ja": APP_NOTICE_JA,
        "packages": sorted_pkgs,
        "services": services,
    }


def render_markdown(payload: dict[str, Any]) -> str:
    lines: list[str] = [
        HEADER_MD,
        "# サードパーティ／外部サービス NOTICE",
        "",
        f"生成時刻 (UTC): `{payload.get('generated_at', '')}`",
        "",
        "## アプリ本体",
        "",
        str(payload.get("app_notice_ja", "")),
        "",
        "## オープンソース依存",
        "",
        "| 名前 | 版 | ライセンス | 系統 |",
        "|------|----|------------|------|",
    ]
    for row in payload.get("packages") or []:
        if not isinstance(row, dict):
            continue
        lines.append(
            f"| {row.get('name', '')} | {row.get('version', '')} | "
            f"{row.get('license', '')} | {row.get('ecosystem', '')} |"
        )
    lines.extend(["", "## 外部サービス（表示・規約メモ）", ""])
    for service in payload.get("services") or []:
        if not isinstance(service, dict):
            continue
        name = service.get("name_ja") or service.get("id") or ""
        status = service.get("status") or ""
        note = service.get("note_ja") or ""
        mark = "要表示" if service.get("attribution_required") else "表示義務なし（メモ）"
        lines.append(f"### {name}")
        lines.append("")
        lines.append(f"- 状態: `{status}` · {mark}")
        if note:
            lines.append(f"- {note}")
        docs_url = service.get("docs_url")
        if isinstance(docs_url, str) and docs_url:
            lines.append(f"- 参考: {docs_url}")
        lines.append("")
    lines.append("再生成: `python scripts/generate_third_party_notices.py`")
    lines.append("画面の `/licenses` は同じ JSON を表示する。")
    lines.append("")
    return "\n".join(lines)


def write_outputs(payload: dict[str, Any]) -> None:
    DOCS_GEN.mkdir(parents=True, exist_ok=True)
    WEB_GEN.mkdir(parents=True, exist_ok=True)
    text = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    (DOCS_GEN / "third_party_notices.json").write_text(text, encoding="utf-8")
    (WEB_GEN / "third_party_notices.json").write_text(text, encoding="utf-8")
    (DOCS_GEN / "third_party_notices.md").write_text(render_markdown(payload), encoding="utf-8")
    readme = DOCS_GEN / "README.md"
    if not readme.is_file():
        readme.write_text(
            "# legal/generated\n\n"
            "`python scripts/generate_third_party_notices.py` が出力する。手編集しない。\n"
            "画面は `apps/web/src/data/generated/third_party_notices.json` と同一内容。\n",
            encoding="utf-8",
        )


def normalize_payload_for_check(payload: dict[str, Any]) -> str:
    clone = json.loads(json.dumps(payload))
    clone.pop("generated_at", None)
    return json.dumps(clone, ensure_ascii=False, sort_keys=True, indent=2) + "\n"


def gather_payload(*, generated_at: str | None = None) -> dict[str, Any]:
    packages = collect_npm_packages() + collect_pip_packages()
    return build_payload(packages, load_services(), generated_at=generated_at or utc_now())


def check_drift() -> int:
    expected = normalize_payload_for_check(gather_payload(generated_at="1970-01-01T00:00:00Z"))
    paths = (
        DOCS_GEN / "third_party_notices.json",
        WEB_GEN / "third_party_notices.json",
    )
    for path in paths:
        if not path.is_file():
            print(f"missing: {path.relative_to(ROOT).as_posix()}", file=sys.stderr)
            return 1
        current = json.loads(path.read_text(encoding="utf-8"))
        if normalize_payload_for_check(current) != expected:
            print(
                f"drift: {path.relative_to(ROOT).as_posix()} "
                "— python scripts/generate_third_party_notices.py を実行して揃える",
                file=sys.stderr,
            )
            return 1
    docs_raw = json.loads((DOCS_GEN / "third_party_notices.json").read_text(encoding="utf-8"))
    web_raw = json.loads((WEB_GEN / "third_party_notices.json").read_text(encoding="utf-8"))
    if normalize_payload_for_check(docs_raw) != normalize_payload_for_check(web_raw):
        print("drift: docs と web の third_party_notices.json が不一致", file=sys.stderr)
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check_drift()
    write_outputs(gather_payload())
    print("wrote docs/legal/generated and apps/web/src/data/generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
